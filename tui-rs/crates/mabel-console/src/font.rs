//! `pprint`: a tiny pixel font, so text can sit anywhere in pixel space.
//!
//! Each glyph is 3×5 pixels; a character takes 4 pixels across (one gap) and a line takes 6.
//! Lowercase letters draw as small capitals (the uppercase shapes). Characters it doesn't
//! know draw as a little box.

use crate::{Frame, Rgb};

pub const ADVANCE: i32 = 4;
pub const LINE: i32 = 6;

/// ' ' (32) to '_' (95), five rows of three pixels each.
