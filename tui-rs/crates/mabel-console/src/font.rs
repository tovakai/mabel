const BOX: [&str; 5] = ["###", "#.#", "#.#", "#.#", "###"];

fn glyph(c: char) -> &'static [&'static str; 5] {
    let c = match c {
        'a'..='z' => c.to_ascii_uppercase(),
        '{' => '(',
        '}' => ')',
        '|' => '!',
        '`' => '\'',
        '~' => '-',
        other => other,
    };
    match c as u32 {
        n @ 32..=95 => &GLYPHS[(n - 32) as usize],
        _ => &BOX,
    }
}

/// How many pixels wide `text`'s longest line is.
pub fn width(text: &str) -> i32 {
    text.lines().map(|l| l.chars().count() as i32 * ADVANCE - 1).max().unwrap_or(0).max(0)
}

/// Draw `text` with its top-left corner at (x, y). `\n` starts a new line.
pub fn pprint(frame: &mut Frame, x: i32, y: i32, text: &str, color: Rgb) {
    let (mut cx, mut cy) = (x, y);
    for c in text.chars() {
        if c == '\n' {
            (cx, cy) = (x, cy + LINE);
            continue;
        }
        for (row, bits) in glyph(c).iter().enumerate() {
            for (col, b) in bits.bytes().enumerate() {
                if b == b'#' {
                    frame.pset(cx + col as i32, cy + row as i32, color);
                }
            }
        }
        cx += ADVANCE;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_land_where_they_should() {
        let mut f = Frame::new(8, 6);
        pprint(&mut f, 0, 0, "Hi", 1);
        assert_eq!((f.pget(0, 0), f.pget(1, 0), f.pget(1, 2)), (1, 0, 1)); // H's sides and bar
        assert_eq!(f.pget(4, 0), 1); // I's top
        assert_eq!(width("Hi"), 7);
        assert_eq!(width("a\nlonger"), 23);
        assert_eq!(glyph('h'), glyph('H'));
        assert_eq!(glyph('é'), &BOX);
    }
}
